#!/usr/bin/env node
/**
 * Generate THIRD_PARTY_NOTICES.md: the license text of every open-source
 * package EZTest ships. That covers code compiled into the Studio bundle
 * (found from esbuild's metafile, so nothing is missed) plus the runtime
 * dependencies installed alongside EZTest, plus optional peer dependencies
 * (database drivers such as oracledb) that are also dev dependencies, so they
 * are always installed where this script runs and the output is stable.
 *
 *   node scripts/third-party-notices.mjs          write the file
 *   node scripts/third-party-notices.mjs --check  exit 1 if it is out of date
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const out = join(root, 'THIRD_PARTY_NOTICES.md');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

/** "node_modules/@scope/name/..." -> "@scope/name" */
function packageOf(path) {
  const parts = relative(root, path).split(sep);
  const i = parts.lastIndexOf('node_modules');
  if (i < 0) return undefined;
  return parts[i + 1].startsWith('@') ? `${parts[i + 1]}/${parts[i + 2]}` : parts[i + 1];
}

async function bundledPackages() {
  const esbuild = await import('esbuild');
  const entries = [join(root, 'src/studio/client/main.ts'), join(root, 'src/studio/client/styles/index.css')];
  const names = new Set(['pdfjs-dist']); // pdf.js is shipped as its own self-hosted module (Assurance viewer)
  for (const entry of entries) {
    const r = await esbuild.build({ entryPoints: [entry], bundle: true, write: false, metafile: true, logLevel: 'silent', platform: 'browser', loader: { '.css': 'css' }, outdir: 'x' });
    for (const input of Object.keys(r.metafile.inputs)) {
      const name = packageOf(join(root, input));
      if (name) names.add(name);
    }
  }
  return names;
}

function licenseText(name) {
  const dir = join(root, 'node_modules', name);
  const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const files = readdirSync(dir).filter((f) => /^(licen[sc]e|copying|notice)(\.|-|$)/i.test(f)).sort();
  const texts = files.map((f) => `#### ${f}\n\n\`\`\`text\n${readFileSync(join(dir, f), 'utf8').trim()}\n\`\`\``);
  const license = meta.license ?? (Array.isArray(meta.licenses) ? meta.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN');
  return { name, version: meta.version, license, homepage: meta.homepage ?? meta.repository?.url ?? '', texts };
}

const bundled = await bundledPackages();
const runtime = new Set(Object.keys(pkg.dependencies ?? {}));
// Optional peers are installed by the user, not by EZTest; credit those we develop and test with.
const peers = new Set(
  Object.keys(pkg.peerDependencies ?? {}).filter((n) => (pkg.devDependencies ?? {})[n] !== undefined && existsSync(join(root, 'node_modules', n, 'package.json'))),
);
const all = [...new Set([...bundled, ...runtime, ...peers])].sort();
const rows = all.map(licenseText);

const missing = rows.filter((r) => !r.texts.length).map((r) => r.name);
const lines = [
  '# Third-party notices',
  '',
  'EZTest is original work. It uses the open-source packages below, each under its own license.',
  'Packages marked **bundled** are compiled into the EZTest Studio files shipped in this package;',
  'packages marked **dependency** are installed alongside EZTest from npm; packages marked **optional peer**',
  'are installed by you only when you use them (e.g. a database driver). This file is generated by',
  '`scripts/third-party-notices.mjs`; do not edit it by hand.',
  '',
  '| Package | Version | License | How it ships |',
  '|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${[bundled.has(r.name) && 'bundled', runtime.has(r.name) && 'dependency', peers.has(r.name) && 'optional peer'].filter(Boolean).join(', ')} |`),
  '',
  ...rows.flatMap((r) => [`## ${r.name} ${r.version} (${r.license})`, '', r.homepage ? `${r.homepage}\n` : '', ...(r.texts.length ? r.texts : ['_No license file in the package; see its package.json._']), '']),
];
const text = lines.join('\n').replace(/\n{3,}/g, '\n\n');

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (current !== text) {
    console.error('THIRD_PARTY_NOTICES.md is out of date. Run: node scripts/third-party-notices.mjs');
    process.exit(1);
  }
  console.log(`THIRD_PARTY_NOTICES.md is up to date (${rows.length} packages).`);
} else {
  writeFileSync(out, text);
  console.log(`wrote THIRD_PARTY_NOTICES.md: ${rows.length} packages (${bundled.size} bundled, ${runtime.size} dependencies, ${peers.size} optional peers)`);
}
if (missing.length) console.warn(`no license file found in: ${missing.join(', ')}`);
