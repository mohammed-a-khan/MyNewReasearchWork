/**
 * EBCDIC code page 037 (US/Canada) <-> Unicode, and the 3270 buffer-address
 * code table. Control code points (0x00-0x3F) display as blanks on a 3270, so
 * they decode to a space; characters with no CP037 code encode to "?".
 */

// Code points for EBCDIC 0x40..0xFF (CP037), 16 per row.
const HIGH: number[] = [
  0x20, 0xa0, 0xe2, 0xe4, 0xe0, 0xe1, 0xe3, 0xe5, 0xe7, 0xf1, 0xa2, 0x2e, 0x3c, 0x28, 0x2b, 0x7c, // 40
  0x26, 0xe9, 0xea, 0xeb, 0xe8, 0xed, 0xee, 0xef, 0xec, 0xdf, 0x21, 0x24, 0x2a, 0x29, 0x3b, 0xac, // 50
  0x2d, 0x2f, 0xc2, 0xc4, 0xc0, 0xc1, 0xc3, 0xc5, 0xc7, 0xd1, 0xa6, 0x2c, 0x25, 0x5f, 0x3e, 0x3f, // 60
  0xf8, 0xc9, 0xca, 0xcb, 0xc8, 0xcd, 0xce, 0xcf, 0xcc, 0x60, 0x3a, 0x23, 0x40, 0x27, 0x3d, 0x22, // 70
  0xd8, 0x61, 0x62, 0x63, 0x64, 0x65, 0x66, 0x67, 0x68, 0x69, 0xab, 0xbb, 0xf0, 0xfd, 0xfe, 0xb1, // 80
  0xb0, 0x6a, 0x6b, 0x6c, 0x6d, 0x6e, 0x6f, 0x70, 0x71, 0x72, 0xaa, 0xba, 0xe6, 0xb8, 0xc6, 0xa4, // 90
  0xb5, 0x7e, 0x73, 0x74, 0x75, 0x76, 0x77, 0x78, 0x79, 0x7a, 0xa1, 0xbf, 0xd0, 0xdd, 0xde, 0xae, // A0
  0x5e, 0xa3, 0xa5, 0xb7, 0xa9, 0xa7, 0xb6, 0xbc, 0xbd, 0xbe, 0x5b, 0x5d, 0xaf, 0xa8, 0xb4, 0xd7, // B0
  0x7b, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47, 0x48, 0x49, 0xad, 0xf4, 0xf6, 0xf2, 0xf3, 0xf5, // C0
  0x7d, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f, 0x50, 0x51, 0x52, 0xb9, 0xfb, 0xfc, 0xf9, 0xfa, 0xff, // D0
  0x5c, 0xf7, 0x53, 0x54, 0x55, 0x56, 0x57, 0x58, 0x59, 0x5a, 0xb2, 0xd4, 0xd6, 0xd2, 0xd3, 0xd5, // E0
  0x30, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0xb3, 0xdb, 0xdc, 0xd9, 0xda, 0x20, // F0 (0xFF is EO: blank)
];

const TO_UNICODE: string[] = new Array<string>(256);
const FROM_UNICODE = new Map<number, number>();
for (let b = 0; b < 256; b++) {
  const cp = b < 0x40 ? 0x20 : HIGH[b - 0x40];
  TO_UNICODE[b] = String.fromCharCode(cp);
  if (b >= 0x40 && b !== 0xff && !FROM_UNICODE.has(cp)) FROM_UNICODE.set(cp, b);
}
FROM_UNICODE.set(0x20, 0x40);

/** One EBCDIC byte as a character (controls and nulls as a blank). */
export function ebcdicToChar(b: number): string {
  return TO_UNICODE[b & 0xff];
}

/** One character as an EBCDIC byte ("?" when CP037 has no code for it). */
export function charToEbcdic(ch: string): number {
  return FROM_UNICODE.get(ch.charCodeAt(0)) ?? 0x6f;
}

export function encodeEbcdic(s: string): Buffer {
  const out = Buffer.alloc(s.length);
  for (let i = 0; i < s.length; i++) out[i] = charToEbcdic(s[i]);
  return out;
}

export function decodeEbcdic(b: Uint8Array): string {
  let s = '';
  for (const x of b) s += TO_UNICODE[x];
  return s;
}

/** True when a character has a CP037 code (so it can be typed on a 3270). */
export function isEbcdicEncodable(ch: string): boolean {
  return FROM_UNICODE.has(ch.charCodeAt(0));
}

/** The 6-bit 3270 code table used for 12-bit buffer addresses, attribute bytes and AIDs. */
export const CODE_TABLE: readonly number[] = [
  0x40, 0xc1, 0xc2, 0xc3, 0xc4, 0xc5, 0xc6, 0xc7, 0xc8, 0xc9, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f,
  0x50, 0xd1, 0xd2, 0xd3, 0xd4, 0xd5, 0xd6, 0xd7, 0xd8, 0xd9, 0x5a, 0x5b, 0x5c, 0x5d, 0x5e, 0x5f,
  0x60, 0x61, 0xe2, 0xe3, 0xe4, 0xe5, 0xe6, 0xe7, 0xe8, 0xe9, 0x6a, 0x6b, 0x6c, 0x6d, 0x6e, 0x6f,
  0xf0, 0xf1, 0xf2, 0xf3, 0xf4, 0xf5, 0xf6, 0xf7, 0xf8, 0xf9, 0x7a, 0x7b, 0x7c, 0x7d, 0x7e, 0x7f,
];

/** Decode a two-byte buffer address (12-bit coded or 14-bit binary). */
export function decodeAddress(b1: number, b2: number): number {
  if ((b1 & 0xc0) === 0) return ((b1 & 0x3f) << 8) | b2;
  return ((b1 & 0x3f) << 6) | (b2 & 0x3f);
}

/** Encode a buffer address: 12-bit coded when it fits (< 4096), else 14-bit binary. */
export function encodeAddress(addr: number): [number, number] {
  if (addr < 4096) return [CODE_TABLE[(addr >> 6) & 0x3f], CODE_TABLE[addr & 0x3f]];
  return [(addr >> 8) & 0x3f, addr & 0xff];
}
