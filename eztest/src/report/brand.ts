/**
 * Report branding (white-label): company, title, subtitle, "prepared by" and
 * footer lines; light and dark logos, a favicon and a small mark; primary,
 * secondary, header and status colours with derived shades that are checked
 * for WCAG AA contrast (a colour that would fail is replaced by an
 * accessible shade, with a warning); a font family with a safe fallback
 * stack and an optional embedded woff2 file; tab and section labels; hidden
 * sections; the EZTest name removed (white label); the default theme.
 *
 * Configured under `report.brand` (any config layer: eztest.config.yaml,
 * projects.<app>.report.brand, config/<env>.yaml) and overridden for CI with
 * a brand file (`--brand-file branding.yaml`, EZTEST_BRAND_FILE or
 * report.brandFile). Every asset is embedded as a data: URI, so report.html
 * stays one self-contained file. Applied to report.html, the PDF, the e-mail
 * summary, the Excel workbook and Studio's Results view (which embeds the
 * report). See docs/reports.md#branding.
 */
