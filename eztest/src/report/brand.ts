// ------------------------------------------------------------------ colour maths

type Rgb = [number, number, number];
const toRgb = (h: string): Rgb => [parseInt(h.slice(1, 3), 16), parseInt(h.slice(3, 5), 16), parseInt(h.slice(5, 7), 16)];
const toHex = (c: Rgb) => `#${c.map((v) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, '0')).join('')}`;
const lin = (v: number) => {
  const s = v / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};
/** WCAG relative luminance of #rrggbb. */
export function luminance(hex: string): number {
  const [r, g, b] = toRgb(hex);
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
}
/** WCAG contrast ratio of two #rrggbb colours (1..21). */
export function contrastRatio(a: string, b: string): number {
  const la = luminance(a);
  const lb = luminance(b);
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
}
/** Mix two colours (t = share of `b`). */
export function mix(a: string, b: string, t: number): string {
  const x = toRgb(a);
  const y = toRgb(b);
  return toHex([x[0] + (y[0] - x[0]) * t, x[1] + (y[1] - x[1]) * t, x[2] + (y[2] - x[2]) * t]);
}
/** The closest shade of `color` (towards black on a light background, white on a dark one) that reaches `ratio` against `bg`. */
export function accessibleShade(color: string, bg: string, ratio = 4.5): string {
  if (contrastRatio(color, bg) >= ratio) return color.toLowerCase();
  const towards = luminance(bg) > 0.4 ? '#000000' : '#ffffff';
  for (let t = 0.04; t <= 1.0001; t += 0.04) {
    const c = mix(color, towards, t);
    if (contrastRatio(c, bg) >= ratio) return c;
  }
  return towards;
}
/** Black or white text, whichever reads better on `bg`. */
export const readableOn = (bg: string): string => (contrastRatio('#ffffff', bg) >= contrastRatio('#16181d', bg) ? '#ffffff' : '#16181d');

/** The report's darkest light surface and lightest dark surface: brand colours are checked against them, so text passes on every surface. */
export const SURFACE = { light: '#eff1f4', dark: '#272b32' } as const;

/** Default status marks (light, dark) and their text shades: all pass AA on the surfaces above. */
const STATUS_DEFAULT: Record<string, { mark: [string, string]; ink: [string, string]; soft: [string, string] }> = {
  passed: { mark: ['#1f8a4c', '#3fb871'], ink: ['#176b3a', '#6fd39a'], soft: ['#e8f5ed', '#16301f'] },
  failed: { mark: ['#d1343b', '#f0616a'], ink: ['#b3262d', '#ff9aa0'], soft: ['#fdecec', '#3a1b1e'] },
  error: { mark: ['#c2571a', '#f08a4b'], ink: ['#9c4211', '#ffb184'], soft: ['#fcefe6', '#37231a'] },
  flaky: { mark: ['#c98a00', '#e6b23a'], ink: ['#7d5600', '#f2c96a'], soft: ['#fdf5e0', '#33291a'] },
  healed: { mark: ['#6a4fd6', '#9c8bf0'], ink: ['#523bb5', '#bdb0f7'], soft: ['#f0edfc', '#262140'] },
  skipped: { mark: ['#8a8f98', '#7d838d'], ink: ['#5b616b', '#b4b9c2'], soft: ['#f1f2f4', '#25282e'] },
};
const DEFAULT_PRIMARY = '#3b5bdb';
const DEFAULT_SECONDARY = '#0c8599';

/**
 * Theme tokens from the brand colours: the primary as mark, its text shade per theme (>= 4.5:1),
 * a soft tint, the text on a primary button; status marks (>= 3:1 for graphics) and their text
 * shades (>= 4.5:1); header background and text. Every substitution is reported in `warnings`.
 */
export function brandPalette(colors: z.infer<typeof BrandColorsSchema> = {}, warnings: string[] = []): BrandPalette {
  const light: ThemeTokens = {};
  const dark: ThemeTokens = {};
  const primary = (colors.primary ?? DEFAULT_PRIMARY).toLowerCase();
  const pLight = accessibleShade(primary, SURFACE.light, 4.5);
  const pDark = accessibleShade(primary, SURFACE.dark, 4.5);
  if (colors.primary && pLight !== primary) warnings.push(`report.brand.colors.primary ${primary} has a contrast of ${contrastRatio(primary, SURFACE.light).toFixed(2)}:1 on the report's light surfaces (WCAG AA needs 4.5:1 for text); links and labels use the accessible shade ${pLight}`);
  const button = contrastRatio(readableOn(pLight), pLight) >= 4.5 ? pLight : accessibleShade(pLight, '#ffffff', 4.5);
  Object.assign(light, { brand: primary, 'brand-ink': pLight, 'brand-soft': mix(primary, SURFACE.light, 0.9), 'brand-btn': button, 'on-brand': readableOn(button), focus: pLight });
  const buttonDark = contrastRatio(readableOn(pDark), pDark) >= 4.5 ? pDark : accessibleShade(pDark, '#16181d', 4.5);
  Object.assign(dark, { brand: accessibleShade(primary, SURFACE.dark, 3), 'brand-ink': pDark, 'brand-soft': mix(primary, SURFACE.dark, 0.8), 'brand-btn': buttonDark, 'on-brand': readableOn(buttonDark), focus: pDark });
  const secondary = (colors.secondary ?? DEFAULT_SECONDARY).toLowerCase();
  const sLight = accessibleShade(secondary, SURFACE.light, 3);
  if (colors.secondary && sLight !== secondary) warnings.push(`report.brand.colors.secondary ${secondary} has a contrast of ${contrastRatio(secondary, SURFACE.light).toFixed(2)}:1 on the report's light surfaces (charts need 3:1); the accessible shade ${sLight} is used`);
  light['series-2'] = sLight;
  dark['series-2'] = accessibleShade(secondary, SURFACE.dark, 3);
  light['series-1'] = accessibleShade(primary, SURFACE.light, 3);
  dark['series-1'] = dark.brand;
  for (const [state, d] of Object.entries(STATUS_DEFAULT)) {
    const c = (colors as Record<string, string | undefined>)[state]?.toLowerCase();
    if (!c) {
      Object.assign(light, { [`st-${state}`]: d.mark[0], [`ink-${state}`]: d.ink[0], [`soft-${state}`]: d.soft[0] });
      Object.assign(dark, { [`st-${state}`]: d.mark[1], [`ink-${state}`]: d.ink[1], [`soft-${state}`]: d.soft[1] });
      continue;
    }
    const markL = accessibleShade(c, SURFACE.light, 3);
    if (markL !== c) warnings.push(`report.brand.colors.${state} ${c} has a contrast of ${contrastRatio(c, SURFACE.light).toFixed(2)}:1 on the report's light surfaces (status marks need 3:1); the accessible shade ${markL} is used`);
    Object.assign(light, { [`st-${state}`]: markL, [`ink-${state}`]: accessibleShade(c, SURFACE.light, 4.5), [`soft-${state}`]: mix(c, SURFACE.light, 0.9) });
    Object.assign(dark, { [`st-${state}`]: accessibleShade(c, SURFACE.dark, 3), [`ink-${state}`]: accessibleShade(c, SURFACE.dark, 4.5), [`soft-${state}`]: mix(c, SURFACE.dark, 0.82) });
  }
  let header: BrandPalette['header'];
  if (colors.headerBackground) {
    const bg = colors.headerBackground.toLowerCase();
    let text = colors.headerText?.toLowerCase() ?? readableOn(bg);
    if (contrastRatio(text, bg) < 4.5) {
      const fallback = readableOn(bg);
      warnings.push(`report.brand.colors.headerText ${text} has a contrast of ${contrastRatio(text, bg).toFixed(2)}:1 on the header background ${bg} (WCAG AA needs 4.5:1); ${fallback} is used`);
      text = fallback;
    }
    header = { bg, text, muted: contrastRatio(mix(text, bg, 0.25), bg) >= 4.5 ? mix(text, bg, 0.25) : text };
  } else if (colors.headerText) warnings.push('report.brand.colors.headerText is ignored without headerBackground');
  return { light, dark, ...(header ? { header } : {}) };
}

/** :root custom properties of a palette (light, dark by preference, dark by choice). */
export function paletteCss(p: BrandPalette | undefined): string {
  if (!p) return '';
  const decl = (t: ThemeTokens) => Object.entries(t).map(([k, v]) => `--${k}:${v}`).join(';');
  const head = p.header ? `.topbar{--head-bg:${p.header.bg};--head-text:${p.header.text};--head-muted:${p.header.muted}}` : '';
  return `:root{${decl(p.light)}}@media (prefers-color-scheme:dark){:root:not([data-theme=light]){${decl(p.dark)}}}:root[data-theme=dark]{${decl(p.dark)}}${head}`;
}

