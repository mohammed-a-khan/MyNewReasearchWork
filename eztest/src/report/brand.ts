type AssetKind = 'logo' | 'logoDark' | 'mark' | 'favicon' | 'font';
const LIMITS: Record<AssetKind, number> = { logo: 512 * 1024, logoDark: 512 * 1024, mark: 256 * 1024, favicon: 128 * 1024, font: 1024 * 1024 };
const TYPES: Record<AssetKind, Record<string, string>> = {
  logo: { '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp', '.gif': 'image/gif' },
  logoDark: { '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp' },
  mark: { '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp' },
  favicon: { '.svg': 'image/svg+xml', '.png': 'image/png', '.ico': 'image/x-icon' },
  font: { '.woff2': 'font/woff2' },
};

function contentMatches(type: string, b: Buffer): boolean {
  if (type === 'image/png') return b.length > 8 && b.readUInt32BE(0) === 0x89504e47;
  if (type === 'image/jpeg') return b.length > 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff;
  if (type === 'image/webp') return b.length > 12 && b.toString('latin1', 0, 4) === 'RIFF' && b.toString('latin1', 8, 12) === 'WEBP';
  if (type === 'image/gif') return b.toString('latin1', 0, 4) === 'GIF8';
  if (type === 'image/x-icon') return b.length > 4 && b.readUInt32BE(0) === 0x00000100;
  if (type === 'font/woff2') return b.toString('latin1', 0, 4) === 'wOF2';
  if (type === 'image/svg+xml') {
    const head = b.toString('utf8', 0, Math.min(b.length, 4096));
    return /<svg[\s>]/i.test(head) && !/<script|\son[a-z]+\s*=|javascript:/i.test(b.toString('utf8'));
  }
  return false;
}

/** A brand asset as a data: URI, checked for its type, its content and its size. */
export async function loadBrandAsset(path: string, kind: AssetKind, key = `report.brand.${kind === 'font' ? 'font.file' : kind}`): Promise<string> {
  const ext = extname(path).toLowerCase();
  const type = TYPES[kind][ext];
  if (!type) throw new EzTestError(`${key} ${path}: use ${Object.keys(TYPES[kind]).join(', ')}`, 'INVALID_BRAND');
  if (!existsSync(path)) throw new EzTestError(`${key} ${path}: file not found`, 'INVALID_BRAND');
  const s = await stat(path);
  if (s.size > LIMITS[kind]) throw new EzTestError(`${key} ${path} is ${Math.ceil(s.size / 1024)} KiB; the limit is ${LIMITS[kind] / 1024} KiB (it is embedded in every report)`, 'INVALID_BRAND');
  const b = await readFile(path);
  if (!contentMatches(type, b)) throw new EzTestError(`${key} ${path} is not a valid ${ext.slice(1).toUpperCase()} file${type === 'image/svg+xml' ? ' (SVG files must not contain scripts or event handlers)' : ''}`, 'INVALID_BRAND');
  return `data:${type};base64,${b.toString('base64')}`;
}

/** The report.* settings branding reads (legacy keys included). */
export interface BrandSettings {
  title?: string;
  name?: string;
  logo?: string;
  brandColor?: string;
  brand?: BrandConfig;
  brandFile?: string;
}

/** Read a brand file (YAML or JSON with the report.brand keys, optionally under `brand:`). Paths in it are relative to it. */
export async function readBrandFile(path: string): Promise<{ brand: BrandConfig; dir: string }> {
  if (!existsSync(path)) throw new EzTestError(`brand file ${path}: file not found`, 'INVALID_BRAND');
  let raw: unknown;
  try {
    raw = parseYaml(await readFile(path, 'utf8'));
  } catch (e) {
    throw new EzTestError(`brand file ${path}: ${(e as Error).message}`, 'INVALID_BRAND');
  }
  const obj = (raw && typeof raw === 'object' && 'brand' in (raw as object) ? (raw as { brand: unknown }).brand : raw) ?? {};
  const r = BrandSchema.safeParse(obj);
  if (!r.success) throw new EzTestError(`brand file ${path}: ${r.error.issues.map((i) => `${i.path.join('.') || '(root)'}: ${i.message}`).join('; ')}`, 'INVALID_BRAND');
  return { brand: obj as BrandConfig, dir: dirname(path) };
}

/**
 * The report branding of a project: report.brand (with the legacy report.name / logo / brandColor),
 * overridden by a brand file. Assets are read and embedded; an invalid or oversized asset is
 * rejected (left out) with its error in `warnings`, as is every colour that was replaced by an
 * accessible shade.
 */
export async function loadBrand(settings: BrandSettings, o: { cwd: string; defaultName: string; brandFile?: string; strict?: boolean }): Promise<{ brand: ReportBrand; title?: string; warnings: string[] }> {
  const warnings: string[] = [];
  let cfg: BrandConfig = { ...(settings.brand ?? {}) };
  const dirOf: Partial<Record<string, string>> = {};
  const file = o.brandFile ?? settings.brandFile;
  if (file) {
    const f = await readBrandFile(resolve(o.cwd, file));
    for (const k of ['logo', 'logoDark', 'favicon', 'mark']) if ((f.brand as Record<string, unknown>)[k]) dirOf[k] = f.dir;
    if (f.brand.font?.file) dirOf.font = f.dir;
    cfg = { ...cfg, ...f.brand, colors: { ...(cfg.colors ?? {}), ...(f.brand.colors ?? {}) }, labels: { ...(cfg.labels ?? {}), ...(f.brand.labels ?? {}), tabs: { ...(cfg.labels?.tabs ?? {}), ...(f.brand.labels?.tabs ?? {}) }, sections: { ...(cfg.labels?.sections ?? {}), ...(f.brand.labels?.sections ?? {}) } } };
  }
  const parsed = BrandSchema.parse(cfg);
  const asset = async (kind: AssetKind, p: string | undefined, key?: string): Promise<string | undefined> => {
    if (!p) return undefined;
    try {
      return await loadBrandAsset(resolve(dirOf[kind === 'font' ? 'font' : kind] ?? o.cwd, p), kind, key);
    } catch (e) {
      if (o.strict) throw e;
      warnings.push((e as Error).message);
      return undefined;
    }
  };
  const logo = await asset('logo', parsed.logo ?? settings.logo, parsed.logo ? undefined : 'report.logo');
  const logoDark = await asset('logoDark', parsed.logoDark);
  const favicon = await asset('favicon', parsed.favicon);
  const mark = await asset('mark', parsed.mark);
  const fontSrc = await asset('font', parsed.font?.file);
  const colors = { ...(settings.brandColor && !parsed.colors?.primary ? { primary: settings.brandColor } : {}), ...(parsed.colors ?? {}) };
  const brand = normalizeBrand({
    name: settings.name ?? o.defaultName,
    ...(parsed.company ? { company: parsed.company } : {}),
    ...(parsed.subtitle ? { subtitle: parsed.subtitle } : {}),
    ...(parsed.preparedBy ? { preparedBy: parsed.preparedBy } : {}),
    ...(parsed.footer ? { footer: parsed.footer } : {}),
    ...(logo ? { logo } : {}),
    ...(logoDark ? { logoDark } : {}),
    ...(favicon ? { favicon } : {}),
    ...(mark ? { mark } : {}),
    ...(Object.keys(colors).length ? { colors } : {}),
    ...(parsed.font ? { font: { family: parsed.font.family, ...(fontSrc ? { src: fontSrc } : {}) } } : {}),
    ...(parsed.labels ? { labels: parsed.labels } : {}),
    ...(parsed.hide.length ? { hide: parsed.hide } : {}),
    ...(parsed.whiteLabel ? { whiteLabel: true } : {}),
    ...(parsed.theme !== 'system' ? { theme: parsed.theme } : {}),
  }, warnings);
  return { brand, ...(parsed.title ? { title: parsed.title } : {}), warnings };
}

const DATA_IMAGE = /^data:image\/(png|jpeg|gif|webp|svg\+xml|x-icon);base64,[A-Za-z0-9+/=]+$/;

/**
 * The model's branding from what a caller passed (already loaded): unsafe values dropped, the
 * palette derived and contrast checked (warnings appended).
 */
export function normalizeBrand(input: Partial<ReportBrand> & { name?: string }, warnings: string[] = []): ReportBrand {
  const colors = { ...(input.colors ?? {}), ...(input.color && /^#[0-9a-f]{6}$/i.test(input.color) && !input.colors?.primary ? { primary: input.color } : {}) };
  const valid = BrandColorsSchema.safeParse(colors);
  const c = valid.success ? valid.data : {};
  const img = (v: string | undefined) => (v && DATA_IMAGE.test(v) ? v : undefined);
  const font = input.font && /^[A-Za-z0-9 _-]{1,64}$/.test(input.font.family) ? { family: input.font.family, ...(input.font.src && /^data:font\/woff2;base64,[A-Za-z0-9+/=]+$/.test(input.font.src) ? { src: input.font.src } : {}) } : undefined;
  const labels = input.labels && BrandLabelsSchema.safeParse(input.labels).success ? input.labels : undefined;
  const hide = (input.hide ?? []).filter((s): s is BrandSection => (BRAND_SECTIONS as readonly string[]).includes(s));
  const out: ReportBrand = {
    name: input.name ?? input.company ?? 'EZTest',
    ...(input.company ? { company: input.company } : {}),
    ...(input.subtitle ? { subtitle: input.subtitle } : {}),
    ...(input.preparedBy ? { preparedBy: input.preparedBy } : {}),
    ...(input.footer ? { footer: input.footer } : {}),
    ...(img(input.logo) ? { logo: input.logo } : {}),
    ...(img(input.logoDark) ? { logoDark: input.logoDark } : {}),
    ...(img(input.favicon) ? { favicon: input.favicon } : {}),
    ...(img(input.mark) ? { mark: input.mark } : {}),
    ...(c.primary ? { color: c.primary } : {}),
    ...(Object.keys(c).length ? { colors: c } : {}),
    ...(font ? { font } : {}),
    ...(labels ? { labels } : {}),
    ...(hide.length ? { hide } : {}),
    ...(input.whiteLabel ? { whiteLabel: true } : {}),
    ...(input.theme === 'light' || input.theme === 'dark' ? { theme: input.theme } : {}),
  };
  if (Object.keys(c).length) out.palette = brandPalette(c, warnings);
  return out;
}
