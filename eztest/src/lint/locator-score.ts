/**
 * Locator quality score: how likely a locator is to keep finding the same
 * element as the application changes. 0 (fragile) .. 100 (robust).
 *
 * Heuristics, in order of robustness:
 *   test ids > role + accessible name > label > placeholder/alt/title >
 *   stable ids and name attributes > visible text > classes > positional and
 *   absolute paths.
 * Dynamic-looking values (generated ids such as ember123, ctl00_, :r5:,
 * j_idt42, hashed CSS classes) and positional predicates cost points.
 * Pure and synchronous: used by the runner, `eztest lint` and the Studio.
 */
import type { LocatorCandidate } from '../core/index.js';

export type LocatorGrade = 'robust' | 'good' | 'fair' | 'weak' | 'fragile';

export interface LocatorScore {
  score: number;
  grade: LocatorGrade;
  reasons: string[];
}

export interface TargetScore extends LocatorScore {
  /** Score of each candidate, in order. */
  candidates: Array<{ candidate: LocatorCandidate; score: number; reasons: string[] }>;
}

/** Values that look generated by a framework or build and change between releases or renders. */
const DYNAMIC = [
  /\b(?:ember|ext-gen|ext-comp|gwt-uid-|yui_|j_idt|ctl\d\d_|mui-|react-select-\d)/i,
  /:r[0-9a-z]+:/, // React useId
  /\b(?:css|sc|jss|emotion|makeStyles)-[a-z0-9]{4,}\b/i, // CSS-in-JS hashed classes
  /[a-f0-9]{8,}/i, // hashes
  /\d{4,}/, // long numbers (record ids, timestamps)
  /[_-]\d{2,}$/, // trailing counters: item_12, row-34
];

export function looksDynamic(v: string): boolean {
  const s = v.replace(/\$\{[^}]+\}/g, ''); // template variables are intentional
  return DYNAMIC.some((re) => re.test(s));
}

export function gradeOf(score: number): LocatorGrade {
  return score >= 85 ? 'robust' : score >= 70 ? 'good' : score >= 50 ? 'fair' : score >= 30 ? 'weak' : 'fragile';
}

const clamp = (n: number) => Math.max(0, Math.min(100, Math.round(n)));

/** Absolute XPath: from the document root (/html/body/...), not a search (//). */
export function isAbsoluteXPath(x: string): boolean {
  const v = x.trim().replace(/^\(+/, '');
  return v.startsWith('/') && !v.startsWith('//');
}

/** Positional XPath: index predicates ([3]), position() or last(). */
export function isPositionalXPath(x: string): boolean {
  return /\[\s*\d+\s*\]|position\s*\(\s*\)|last\s*\(\s*\)/.test(x);
}

function scoreXPath(x: string, reasons: string[]): number {
  if (isAbsoluteXPath(x)) {
    reasons.push('absolute XPath from the document root breaks on any layout change');
    return isPositionalXPath(x) ? 3 : 8;
  }
  let s: number;
  if (/@data-(?:testid|test-id|test|qa|cy)\s*=/.test(x)) { s = 88; reasons.push('XPath on a test id'); }
  else if (/@id\s*=/.test(x)) { s = 72; reasons.push('XPath on an id'); }
  else if (/@(?:name|aria-label|for)\s*=/.test(x)) { s = 68; reasons.push('XPath on name/aria-label'); }
  else if (/text\(\)|normalize-space\(|contains\(\s*\./.test(x)) { s = 45; reasons.push('XPath on visible text (breaks on copy changes and translations)'); }
  else if (/@class/.test(x)) { s = 40; reasons.push('XPath on CSS classes'); }
  else if (/@\w/.test(x)) { s = 55; reasons.push('XPath on an attribute'); }
  else { s = 25; reasons.push('XPath on structure only'); }
  if (isPositionalXPath(x)) { s = Math.min(s, 25) - 5; reasons.push('positional predicate ([n], position(), last()) depends on element order'); }
  if (/(?:ancestor|following|preceding)(?:-sibling)?::/.test(x)) { s -= 12; reasons.push('relative axes (following/preceding/ancestor) depend on layout'); }
  const steps = x.split(/\/\/?/).filter(Boolean).length;
  if (steps > 4) { s -= 8; reasons.push(`${steps} path steps`); }
  if (/\/\/\*/.test(x)) s -= 3;
  const lit = [...x.matchAll(/(['"])(.*?)\1/g)].map((m) => m[2]);
  if (lit.some(looksDynamic)) { s -= 35; reasons.push('dynamic-looking value (generated id or number)'); }
  return s;
}

function scoreCss(c: string, reasons: string[]): number {
  const v = c.trim();
  let s: number;
  if (/\[data-(?:testid|test-id|test|qa|cy)\s*[~|^$*]?=/.test(v)) { s = 92; reasons.push('CSS on a test id'); }
  else if (/^#[\w-]+$/.test(v) || /^[a-z]+#[\w-]+$/i.test(v)) { s = 78; reasons.push('CSS id selector'); }
  else if (/\[(?:name|aria-label|for|type)\s*=/.test(v)) { s = 70; reasons.push('CSS on name/aria-label'); }
  else if (/#[\w-]+/.test(v)) { s = 65; reasons.push('CSS with an id'); }
  else if (/\[[\w-]+/.test(v)) { s = 58; reasons.push('CSS on an attribute'); }
  else if (/\.[\w-]+/.test(v)) { s = 45; reasons.push('CSS on classes (styling, not identity)'); }
  else { s = 18; reasons.push('CSS on tag names only'); }
  if (/:nth-(?:child|of-type)|:first-child|:last-child|:eq\(/.test(v)) { s = Math.min(s, 30) - 5; reasons.push('positional pseudo-class depends on element order'); }
  const depth = v.split(/\s*[>+~]\s*|\s+/).filter(Boolean).length;
  if (depth > 3) { s -= 10; reasons.push(`${depth}-level selector chain`); }
  const ids = [...v.matchAll(/#([\w-]+)|\.([\w-]+)|=\s*["']?([^"'\]]+)/g)].map((m) => m[1] ?? m[2] ?? m[3]);
  if (ids.some((x) => x && looksDynamic(x))) { s -= 35; reasons.push('dynamic-looking id or class (generated)'); }
  return s;
}

/** Score one locator candidate. */
export function scoreLocator(c: LocatorCandidate): LocatorScore {
  const reasons: string[] = [];
  let s: number;
  switch (c.strategy) {
    case 'testId':
      s = looksDynamic(c.value) ? 55 : 95;
      reasons.push(looksDynamic(c.value) ? 'test id looks generated' : 'test id (made for testing)');
      break;
    case 'role':
      if (c.name) {
        s = 90;
        reasons.push('role + accessible name (what users and assistive tech see)');
        if (looksDynamic(c.name)) { s -= 30; reasons.push('the name contains a dynamic value'); }
      } else {
        s = 35;
        reasons.push('role without a name matches every element of that role');
      }
      break;
    case 'label': s = 85; reasons.push('form label'); break;
    case 'placeholder': s = 70; reasons.push('placeholder text (often reworded)'); break;
    case 'altText': s = 72; reasons.push('image alt text'); break;
    case 'title': s = 62; reasons.push('title attribute'); break;
    case 'section': s = 74; reasons.push('container named by its heading, legend or accessible name'); break;
    case 'text':
      s = c.exact === false ? 45 : 55;
      reasons.push('visible text only (breaks on copy changes and translations)');
      if (looksDynamic(c.value)) { s -= 25; reasons.push('the text contains a dynamic value'); }
      break;
    // Native apps (docs/mobile.md): accessibility ids are the test ids of mobile.
    case 'accessibilityId':
      s = looksDynamic(c.value) ? 55 : 93;
      reasons.push(looksDynamic(c.value) ? 'accessibility id looks generated' : 'accessibility id (stable, set for testing and assistive tech)');
      break;
    case 'id':
      s = looksDynamic(c.value) ? 40 : 80;
      reasons.push(looksDynamic(c.value) ? 'native id looks generated' : 'native resource id');
      break;
    case 'iosPredicate': s = 60; reasons.push('NSPredicate (stable when it uses name/label, fragile on values)'); break;
    case 'className': s = 15; reasons.push('class name only matches every element of that type'); break;
    case 'css': s = scoreCss(c.value, reasons); break;
    case 'xpath': s = scoreXPath(c.value, reasons); break;
  }
  const score = clamp(s);
  return { score, grade: gradeOf(score), reasons };
}

/** Score a target: its best candidate, plus a little for having fallbacks. */
export function scoreTarget(locators: LocatorCandidate[]): TargetScore {
  if (!locators.length) return { score: 0, grade: 'fragile', reasons: ['no locator candidates'], candidates: [] };
  const candidates = locators.map((c) => {
    const r = scoreLocator(c);
    return { candidate: c, score: r.score, reasons: r.reasons };
  });
  const best = candidates.reduce((a, b) => (b.score > a.score ? b : a));
  const bonus = Math.min(5, 2 * (candidates.filter((c) => c.score >= 50).length - 1));
  const score = clamp(best.score + Math.max(0, bonus));
  return { score, grade: gradeOf(score), reasons: best.reasons, candidates };
}

/** True when a candidate relies only on visible text (breaks on translated UIs). */
export function isTextOnly(c: LocatorCandidate): boolean {
  if (c.strategy === 'text') return true;
  if (c.strategy === 'xpath') return /text\(\)|normalize-space\(\s*\)|contains\(\s*\.\s*,/.test(c.value) && !/@(?:id|name|data-[\w-]+|aria-label|for)\s*=/.test(c.value);
  if (c.strategy === 'css') return /:has-text\(|:text\(/.test(c.value);
  return false;
}

/** Human-readable form of a candidate (same as the runner's describeCandidate), e.g. `role=button "Sign in"`. */
export function describeCandidateText(c: LocatorCandidate): string {
  return c.strategy === 'role' && c.name !== undefined ? `role=${c.value} "${c.name}"` : `${c.strategy}=${JSON.stringify(c.value)}`;
}
